def build(name: str) -> Canvas:
    rows = ICONS[name]
    assert len(rows) == 16, f"{name}: {len(rows)} lignes"
    c = Canvas(16, 16)
    for y, row in enumerate(rows):
        row = row.ljust(16, ".")[:16]
        for x, ch in enumerate(row):
            if ch in LEGEND:
                c.set(x, y, LEGEND[ch])
    return c


def export(out_dir: str, scale: int = 2) -> list:
    names = []
    for name in ICONS:
        rows = ICONS[name]
        for i, r in enumerate(rows):
            if len(r) != 16:
                print(f"  [icône {name}] ligne {i} de longueur {len(r)} (ajustée)")
        build(name).save(f"{out_dir}/{name}.png", scale)
        names.append(name)
    return names
